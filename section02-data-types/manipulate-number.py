score = 0
height = 1.8
# An f-string lets you insert variables or expressions \
# directly into a string by placing them inside curly braces {}.
print(f"your score is {score}, your height is {height}")

print("Your score is " + str(score) + ", your height is " + str(height))

print("Your score is {}, your height is {}".format(score, height))
